-- =====================================================================
-- 017_registry_hn_pad.sql : HN ในทะเบียนที่นำเข้าไว้แล้ว เติม 0 ด้านหน้าให้ครบ 9 หลัก
-- (การนำเข้าครั้งต่อไปเติมให้อัตโนมัติตามค่า HN_LENGTH ใน .env)
-- =====================================================================
UPDATE registry_rows SET hn = lpad(hn, 9, '0') WHERE hn ~ '^[0-9]{1,8}$';
